"""
Step 2 of draft self-distillation: record what OUR target model actually says.

harvest_prompts.py collected real prompts from Hugging Face and deliberately
threw away their reference answers, because those were written by other models.
A draft model's job is not to be right -- it is to guess the next token our
deployed target would emit. So the training targets have to come from the target
itself, in exactly the configuration it is served in:

  * the Q4_K_M quantization we actually run, not a BF16 copy. If quantization
    shifts the output distribution, the draft must learn the shifted one.
  * the same `-ot` expert-offload split, greedy sampling, same chat template.

That is what makes this "self-training": the labels are generated by the system
being sped up, so the draft converges on the target's behaviour rather than on
some other model's.

Output is JSONL, one record per prompt, holding the token ids (not just text) so
training operates on exactly the sequence the draft will have to predict --
re-tokenizing text would introduce boundary mismatches that quietly corrupt the
labels.

Resumable: re-running skips prompts already present in the output file, since a
full capture run is hours of 30B generation.
"""
import argparse
import json
import os
import subprocess
import sys
import time
import urllib.request

AI2 = "/home/everett/AI2"
BACKEND = "/home/everett/.lmstudio/extensions/backends/llama.cpp-linux-x86_64-nvidia-cuda12-avx2-2.37.0"
VENDOR = "/home/everett/.lmstudio/extensions/backends/vendor/linux-llama-cuda12-vendor-v1"
SERVER = os.path.join(BACKEND, "llama-server")
BIG = "/home/everett/.lmstudio/models/lmstudio-community/Qwen3-30B-A3B-Instruct-2507-GGUF/Qwen3-30B-A3B-Instruct-2507-Q4_K_M.gguf"
PORT = 8095

CHAT = "<|im_start|>user\n{p}<|im_end|>\n<|im_start|>assistant\n"


def wait_healthy(proc, timeout=420):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if proc.poll() is not None:
            return False
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{PORT}/health", timeout=3) as r:
                if r.status == 200:
                    return True
        except Exception:
            time.sleep(2)
    return False


def post(path, payload, timeout=900):
    req = urllib.request.Request(f"http://127.0.0.1:{PORT}{path}",
                                 data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prompts", default=os.path.join(AI2, "data", "draft_train_prompts.jsonl"))
    ap.add_argument("--out", default=os.path.join(AI2, "data", "draft_train_capture.jsonl"))
    ap.add_argument("--max-tokens", type=int, default=256)
    ap.add_argument("--limit", type=int, default=0, help="0 = all")
    ap.add_argument("--n-cpu-moe", type=int, default=48,
                    help="must match the split the target is actually served with")
    args = ap.parse_args()

    if not os.path.exists(args.prompts):
        print(f"missing {args.prompts} -- run harvest_prompts.py first", file=sys.stderr)
        sys.exit(1)

    prompts = [json.loads(l)["prompt"] for l in open(args.prompts)]
    if args.limit:
        prompts = prompts[:args.limit]

    done = set()
    if os.path.exists(args.out):
        for line in open(args.out):
            try:
                done.add(json.loads(line)["prompt"])
            except Exception:
                continue
        print(f"resuming: {len(done)} already captured", file=sys.stderr)
    todo = [p for p in prompts if p not in done]
    if not todo:
        print("nothing to do")
        return

    log_path = os.path.join(AI2, "state", "capture_target.log")
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)

    cmd = [SERVER, "-m", BIG, "--port", str(PORT), "-ngl", "999",
           "--n-cpu-moe", str(args.n_cpu_moe),
           "-c", "4096", "-fa", "on", "-t", "16", "--no-warmup"]
    env = dict(os.environ)
    env["LD_LIBRARY_PATH"] = f"{VENDOR}:{BACKEND}"

    t_start = time.time()
    with open(log_path, "w") as logf:
        proc = subprocess.Popen(cmd, stdout=logf, stderr=subprocess.STDOUT, env=env)
        try:
            if not wait_healthy(proc):
                proc.kill()
                print("server never became healthy; see " + log_path, file=sys.stderr)
                sys.exit(1)

            with open(args.out, "a") as out:
                for i, p in enumerate(todo, 1):
                    text = CHAT.format(p=p)
                    try:
                        # Greedy: the draft is learning the target's argmax path,
                        # which is also what speculative verification compares
                        # against at temperature 0.
                        r = post("/completion", {
                            "prompt": text, "n_predict": args.max_tokens,
                            "temperature": 0, "cache_prompt": False,
                        })
                        prompt_ids = post("/tokenize", {"content": text})["tokens"]
                        completion_ids = post("/tokenize", {"content": r["content"]})["tokens"]
                    except Exception as e:
                        print(f"  [{i}/{len(todo)}] failed: {e}", file=sys.stderr)
                        continue
                    out.write(json.dumps({
                        "prompt": p,
                        "prompt_text": text,
                        "completion": r["content"],
                        "prompt_ids": prompt_ids,
                        "completion_ids": completion_ids,
                    }) + "\n")
                    out.flush()
                    if i % 10 == 0 or i == len(todo):
                        rate = i / (time.time() - t_start)
                        eta = (len(todo) - i) / rate / 60 if rate else 0
                        print(f"  [{i}/{len(todo)}] {rate*60:.1f} prompts/min, "
                              f"eta {eta:.0f} min", file=sys.stderr)
        finally:
            proc.terminate()
            try:
                proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait(timeout=10)

    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
